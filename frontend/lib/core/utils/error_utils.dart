/// Tra bản dịch; key dạng "error.x.y.<chi tiết>" thử lại với phần đầu "error.x.y".
/// Key có tham số: "error.x.y|a|b" → thay {0}, {1} trong bản dịch.
String? _translateKey(String raw, bool en) {
  final parts = raw.split('|');
  final base = _lookupKey(parts.first, en);
  if (base == null) return null;
  var out = base;
  for (var i = 1; i < parts.length; i++) {
    // Tham số là một mã lỗi khác (vd. "error.contract.import_row|HD-1|error.contract.overlap|HD-0") → dịch phần còn lại
    if (parts[i].startsWith('error.')) {
      final rest = parts.sublist(i).join('|');
      out = out.replaceAll('{${i - 1}}', _translateKey(rest, en) ?? rest);
      break;
    }
    out = out.replaceAll('{${i - 1}}', parts[i]);
  }
  // Thiếu tham số (BE cũ không gửi chi tiết) → bỏ chỗ trống và dấu nối trước nó
  return out
      .replaceAll(RegExp(r'\s*(?:[:—-]\s*)?(?:của\s+|for\s+)?\{\d+\}'), '')
      .trim();
}

String? _lookupKey(String key, bool en) {
  final map = en ? _enMessages : _viMessages;
  var k = key;
  while (true) {
    final hit = map[k];
    if (hit != null) return hit;
    final dot = k.lastIndexOf('.');
    if (dot <= 'error.'.length) return null;
    k = k.substring(0, dot);
  }
}

/// Chỉ cho test: tra bản dịch đúng như khi hiển thị (kể cả lùi về tiền tố ngắn hơn).
@visibleForTesting
String? debugLookupServerKey(String key, {required bool english}) => _lookupKey(key, english);

/// Dịch một mã lỗi backend đơn lẻ (vd. lý do trong danh sách xung đột); không có bản dịch thì trả nguyên.
String serverKeyMsg(String key) => _translateKey(key, LanguageService.instance.isEnglish) ?? key;

String serverMsg(dynamic e) {
  final en = LanguageService.instance.isEnglish;

  if (e is DioException && e.response == null) {
    return en
        ? 'Unable to connect to server, please check your network'
        : 'Không thể kết nối server, kiểm tra kết nối mạng';
  }

  if (e is DioException) {
    final status = e.response?.statusCode;
    final code = status ?? 0;
    final data = e.response?.data;

    String? msg;
    if (data is Map) {
      msg = (data['message'] as String?)?.trim();
      if (msg == null || msg.isEmpty) {
        msg = (data['error'] as String?)?.trim();
      }
    } else if (data is String && data.trim().isNotEmpty) {
      msg = data.trim();
    }

    if (msg != null && msg.isNotEmpty) {
      final translated = _translateKey(msg, en);
      if (translated != null) return translated;
      // Key lỗi chưa có bản dịch → không hiện "error.xxx" thô cho người dùng (F6)
      if (!msg.startsWith('error.') && !msg.startsWith('warning.')) return msg;
    }

    return switch (code) {
      400 => en ? 'Invalid data' : 'Dữ liệu không hợp lệ',
      401 => en
          ? 'Session expired, please sign in again'
          : 'Phiên đăng nhập hết hạn, vui lòng đăng nhập lại',
      403 => en
          ? 'You do not have permission to perform this action'
          : 'Không có quyền thực hiện thao tác này',
      404 => en ? 'Data not found' : 'Không tìm thấy dữ liệu',
      409 => en
          ? 'Data conflict, please check again'
          : 'Xung đột dữ liệu, vui lòng kiểm tra lại',
      500 => en ? 'Server error, please try again later' : 'Lỗi server, vui lòng thử lại sau',
      _ => en ? 'Unknown error (code $code)' : 'Lỗi không xác định (mã $code)',
    };
  }

  // Lỗi trong app (dữ liệu không đúng dạng…), không phải lỗi mạng — trước đây báo nhầm "không kết nối được"
  debugPrint('serverMsg: lỗi không phải từ server: $e');
  return en
      ? 'Something went wrong, please try again'
      : 'Có lỗi xảy ra, vui lòng thử lại';
}
