ALTER TABLE permissions ADD COLUMN required_rule VARCHAR(50) NULL;

-- EMPLOYEE module
UPDATE permissions SET required_rule = 'EMPLOYEE_VIEW' WHERE code IN ('EMPLOYEE_CREATE', 'EMPLOYEE_UPDATE', 'EMPLOYEE_DELETE');

-- DEPARTMENT module
UPDATE permissions SET required_rule = 'DEPARTMENT_VIEW' WHERE code IN ('DEPARTMENT_MANAGE', 'POSITION_MANAGE');

-- ATTENDANCE module
UPDATE permissions SET required_rule = 'ATTENDANCE_VIEW' WHERE code IN ('ATTENDANCE_MANAGE', 'ATTENDANCE_SELF', 'ATTENDANCE_REQUEST_APPROVE');

-- SHIFT module
UPDATE permissions SET required_rule = 'SHIFT_VIEW' WHERE code = 'SHIFT_MANAGE';

-- PAYROLL module
UPDATE permissions SET required_rule = 'PAYROLL_VIEW' WHERE code IN ('PAYROLL_CREATE', 'PAYROLL_APPROVE', 'PAYROLL_PAY');

-- ROLE module
UPDATE permissions SET required_rule = 'ROLE_VIEW' WHERE code = 'ROLE_MANAGE';

-- LEAVE module (tree: LEAVE_VIEW → LEAVE_TYPE_VIEW → LEAVE_TYPE_MANAGE; LEAVE_VIEW → LEAVE_ACCRUAL_VIEW → LEAVE_ACCRUAL_MANAGE)
UPDATE permissions SET required_rule = 'LEAVE_VIEW'        WHERE code IN ('LEAVE_REQUEST_CREATE', 'LEAVE_REQUEST_APPROVE', 'LEAVE_GRANT_MANUAL', 'LEAVE_TYPE_VIEW', 'LEAVE_ACCRUAL_VIEW');
UPDATE permissions SET required_rule = 'LEAVE_TYPE_VIEW'   WHERE code = 'LEAVE_TYPE_MANAGE';
UPDATE permissions SET required_rule = 'LEAVE_ACCRUAL_VIEW' WHERE code = 'LEAVE_ACCRUAL_MANAGE';
